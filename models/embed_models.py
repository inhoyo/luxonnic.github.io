"""
Embeds the GLB files exported by build_stations.py into a classic script,
so the landing page can load them from disk (file://) without fetch().

Usage (from the repo root):
  python models/embed_models.py <dir with power.glb and signal.glb>
Writes assets/stations-models.js.
"""

import base64
import os
import sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "stations-models.js")

parts = []
for key in ("power", "signal"):
    with open(os.path.join(src, key + ".glb"), "rb") as f:
        parts.append('  "%s": "%s"' % (key, base64.b64encode(f.read()).decode("ascii")))

with open(out, "w", encoding="utf8") as f:
    f.write("/* Generated by models/embed_models.py from models/build_stations.py. Do not edit. */\n")
    f.write("window.LUX_STATIONS = {\n" + ",\n".join(parts) + "\n};\n")

print("wrote", os.path.normpath(out), os.path.getsize(out), "bytes")
